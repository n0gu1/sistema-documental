const { chromium } = require(process.env.PLAYWRIGHT_MODULE)
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext()
  const page = await context.newPage()
  page.setDefaultTimeout(60000)
  const base = 'http://localhost:5173'
  const code = `REQ13_${Date.now()}`
  const name = `Prueba rol ${code}`
  try {
    await page.goto(`${base}/static/`)
    await page.getByLabel('Correo o usuario').fill('prueba.admin@test.local')
    await page.locator('#password').fill(process.env.USER_TEST_PASSWORD)
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await page.getByRole('button', { name: 'Roles y permisos', exact: true }).click()
    await page.getByRole('button', { name: 'Nuevo rol', exact: true }).click()
    const create = page.locator('.roles-create-panel')
    await create.getByLabel('Código', { exact: true }).fill(code)
    await create.getByLabel('Nombre', { exact: true }).fill(name)
    await create.getByLabel('Descripción', { exact: true }).fill('Prueba requisitos 13 y 14')
    const pending = page.waitForResponse(r => r.url().endsWith('/api/admin/roles/') && r.request().method() === 'POST')
    await create.getByRole('button', { name: 'Crear rol', exact: true }).click()
    const response = await pending
    assert.equal(response.status(), 201)
    const { role } = await response.json()
    async function post(data) {
      const csrf = await (await context.request.get(`${base}/api/auth/csrf/`)).json()
      return context.request.post(`${base}/api/admin/roles/`, { headers: { 'X-CSRFToken': csrf.csrf_token }, data })
    }
    const duplicateCode = await post({ code, name: `${name} diferente` })
    assert.equal(duplicateCode.status(), 409)
    const duplicateName = await post({ code: `${code}_OTRO`, name })
    assert.equal(duplicateName.status(), 409)
    await page.getByRole('row').filter({ hasText: name }).click()
    await page.getByRole('button', { name: 'Editar rol seleccionado', exact: true }).click()
    const edit = page.locator('.roles-edit-panel')
    await edit.getByLabel('Nombre', { exact: true }).fill(`${name} editado`)
    await edit.getByLabel('Descripción', { exact: true }).fill('Descripción modificada')
    await edit.getByLabel('Estado del rol', { exact: true }).selectOption('false')
    const updated = page.waitForResponse(r => r.url().endsWith(`/roles/${role.id}/`) && r.request().method() === 'PATCH')
    await edit.getByRole('button', { name: 'Guardar rol', exact: true }).click()
    assert.equal((await updated).status(), 200)
    await page.getByText('Rol actualizado correctamente.', { exact: true }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Roles y permisos', exact: true }).click()
    const row = page.getByRole('row').filter({ hasText: `${name} editado` })
    await row.waitFor()
    assert.match(await row.innerText(), /Inactivo/)
    assert.match(await row.innerText(), /Descripción modificada/)
    const list = await (await context.request.get(`${base}/api/admin/roles/?include_inactive=true`)).json()
    const persisted = list.roles.find(item => item.id === role.id)
    assert.equal(persisted.nombre, `${name} editado`)
    assert.equal(persisted.activo, false)
    assert.equal(persisted.codigo, code)
    assert.equal(persisted.permissions_count, 0)
    const existing = list.roles.find(item => item.id !== role.id)
    const csrf = await (await context.request.get(`${base}/api/auth/csrf/`)).json()
    const duplicateUpdate = await context.request.patch(`${base}/api/admin/roles/${role.id}/`, { headers: { 'X-CSRFToken': csrf.csrf_token }, data: { name: existing.nombre } })
    assert.equal(duplicateUpdate.status(), 409)
    const result = { status: 'PASS', role_id: role.id, test_role_code: code, create: 201, duplicate_code: 409, duplicate_name: 409, duplicate_name_patch: 409, edit: 200, persisted_after_reload: true, test_role_inactive_without_permissions: true }
    fs.writeFileSync(path.join(__dirname, 'resultado_roles_edicion.json'), JSON.stringify(result, null, 2))
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
