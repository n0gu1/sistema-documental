const { chromium } = require('C:/Users/Cristian/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({headless:true})
  const page = await browser.newPage({viewport:{width:1440,height:1080}})
  page.setDefaultTimeout(60000)
  const base = 'http://127.0.0.1:5173'
  try {
    await page.goto(base+'/static/')
    await page.getByLabel('Correo o usuario').fill('prueba.admin@test.local')
    await page.locator('#password').fill(process.env.DOCUMENT_TEST_PASSWORD)
    const login = page.waitForResponse(r=>r.url().endsWith('/api/auth/login/') && r.request().method()==='POST')
    await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
    assert.equal((await login).status(),200)
    const request = page.context().request
    const catalogs = await (await request.get(base+'/api/documents/catalogs/')).json()
    const csrf = await (await request.get(base+'/api/auth/csrf/')).json()
    const code = 'REQ24-UI-'+Date.now()
    const created = await request.post(base+'/api/documents/',{headers:{'X-CSRFToken':csrf.csrf_token},data:{code,title:code,area_id:catalogs.areas[0].id,type_id:catalogs.types[0].id,metadata:{observations:'Historia conservada requisito 24'}}})
    assert.equal(created.status(),201,await created.text())
    const document = (await created.json()).document
    await page.getByRole('button',{name:'Documentos',exact:true}).click()
    const button = page.getByRole('button',{name:`Archivar ${code}`,exact:true})
    await button.click()
    const dialog = page.getByRole('dialog',{name:`Archivar documento ${code}`,exact:true})
    assert.equal(await dialog.getByRole('button',{name:'Confirmar archivo',exact:true}).isDisabled(),true)
    await dialog.getByRole('button',{name:'Cancelar',exact:true}).click()
    assert.equal((await request.get(`${base}/api/documents/${document.id}/`)).status(),200)
    await button.click()
    const reason = 'Fin de vigencia: prueba UI requisito 24'
    await dialog.getByLabel('Motivo del archivo').fill(reason)
    const response = page.waitForResponse(r=>r.url().endsWith(`/api/documents/${document.id}/archive/`) && r.request().method()==='POST')
    await dialog.getByRole('button',{name:'Confirmar archivo',exact:true}).click()
    assert.equal((await response).status(),200)
    await page.getByRole('status').filter({hasText:`Documento ${code} archivado.`}).waitFor()
    await button.waitFor({state:'detached'})
    await page.reload()
    await page.getByRole('button',{name:'Documentos',exact:true}).click()
    await page.getByPlaceholder('Buscar por código, título o palabras clave...').fill(code)
    await page.waitForResponse(r=>r.url().includes('/api/documents/?') && r.url().includes(code.toLowerCase()))
    assert.equal(await button.count(),0)
    const normal = await (await request.get(base+'/api/documents/?search='+code)).json()
    assert.equal(normal.count,0)
    const archived = await (await request.get(base+'/api/documents/?include_archived=true&search='+code)).json()
    assert.equal(archived.count,1)
    assert.equal(archived.results[0].id,document.id)
    assert.ok(archived.results[0].archived_at)
    await page.screenshot({path:'docs/archivo_documental_ui.png',fullPage:true})
    const result={result:'PASS',document_id:document.id,code,reason,checks:['Alta real por API','Cancelar conserva documento activo','Motivo requerido en UI','Archivar mediante POST con ID seleccionado','Recargar: ausente del listado normal, presente al incluir archivados']}
    fs.writeFileSync('docs/resultado_archivo_documental_ui.json',JSON.stringify(result,null,2))
    console.log(JSON.stringify(result))
  } catch(error) { await page.screenshot({path:'docs/archivo_documental_error.png'}); throw error }
  finally { await browser.close() }
})()
